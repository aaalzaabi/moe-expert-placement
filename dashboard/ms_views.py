def run_scenario(key: str, Y: np.ndarray, eval_windows: int = U.DAY) -> dict:
    """Run the real use-case pipeline (forecast evaluation + agent) on a shortened evaluation window.
    In memory only: nothing is written to disk."""
    uc = U.USE_CASES[key]
