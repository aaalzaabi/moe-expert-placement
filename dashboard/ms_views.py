def validate_forecast(pred: np.ndarray, H: int, S: int, E: int) -> np.ndarray:
    pred = np.asarray(pred, float)
    if pred.shape != (H, S, E):
        raise ValueError(f"forecast shape {pred.shape} != expected {(H, S, E)}")
    if not np.isfinite(pred).all():
        raise ValueError("forecast contains NaN or infinite values")
    if (pred < 0).any():
        raise ValueError("forecast contains negative demand")
    return pred


def predicted_vs_actual(Y: np.ndarray, fitted: dict, key: str, site: int, expert: int | None = None,
                        eval_windows: int = U.DAY) -> pd.DataFrame:
    """For each decision point in the evaluation period, the H forecasts vs what arrived.
    expert=None -> site volume (sum over experts)."""
    uc = U.USE_CASES[key]
    H = U.spec().horizon
    rows = []
    for t in F.decision_points(uc.train_end, min(uc.T, uc.train_end + eval_windows), H):
        fut = Y[t + 1:t + H + 1, site]
        actual = fut.sum(axis=1) if expert is None else fut[:, expert]
        preds = {}
        for m, f in fitted.items():
            p = validate_forecast(f.predict(t, H), H, Y.shape[1], Y.shape[2])[:, site]
            preds[m] = p.sum(axis=1) if expert is None else p[:, expert]
        for h in range(H):
            rows.append({"window": t + 1 + h, "decision_t": t, "actual": float(actual[h]),
                         **{m: float(v[h]) for m, v in preds.items()}})
    return pd.DataFrame(rows)


def error_by_site(Y: np.ndarray, fitted: dict, key: str, eval_windows: int = U.DAY) -> pd.DataFrame:
    uc = U.USE_CASES[key]
    H = U.spec().horizon
    acc = []
    for t in F.decision_points(uc.train_end, min(uc.T, uc.train_end + eval_windows), H):
        ybar = Y[t + 1:t + H + 1].mean(0)
        for m, f in fitted.items():
            yh = f.predict(t, H).mean(0)
            for s, site in enumerate(uc.topology.sites):
                acc.append({"model": m, "site": site.name, "wape": F.wape(ybar[s], yh[s]),
                            "popularity_error": F.popularity_error(ybar[s:s + 1], yh[s:s + 1])})
    if not acc:
        return pd.DataFrame(columns=["model", "site", "wape", "popularity_error"])
    return pd.DataFrame(acc).groupby(["model", "site"], as_index=False).mean()


