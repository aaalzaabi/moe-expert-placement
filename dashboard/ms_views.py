# ------------------------------------------------------------------ regret & drift
QUADRANTS = {
    (False, False): "fine (low error, no regret)",
    (True, False): "harmless error (high error, no regret)",
    (False, True): "harmful small error (low error, real regret)",
    (True, True): "harmful large error",
}


def classify(rows: pd.DataFrame | None, tau_err: float = 0.10, tau_regret: float = 0.02) -> pd.DataFrame:
    if rows is None or rows.empty:
        return pd.DataFrame(columns=["model", "t", "wape", "regret_rel", "quadrant"])
    r = rows.copy()
    r["quadrant"] = [QUADRANTS[(bool(w > tau_err), bool(g > tau_regret))] for w, g in zip(r.wape, r.regret_rel)]
    r["regret_basis"] = HINDSIGHT
    return r


def capacity_violations(rows: pd.DataFrame | None, util_cap: float | None) -> pd.DataFrame:
    """Two definitions, both reported: overload = utilisation >= 1 (demand exceeds capacity);
    above cap = utilisation above the locality-mode cap (policy limit, not a physical overload)."""
    if rows is None or rows.empty or "J_forecast_plan" not in rows:
        return pd.DataFrame(columns=["model", "decision_points", "overload (util >= 1)", "above cap"])
    out = []
    for m, g in rows.groupby("model"):
        out.append({"model": m, "decision_points": len(g),
                    "overload (util >= 1)": int((g.J_forecast_plan >= 1).sum()),
                    "above cap": int((g.J_forecast_plan > util_cap).sum()) if util_cap is not None else 0})
    return pd.DataFrame(out)


def drift_alerts(rows: pd.DataFrame | None, tau_regret: float = 0.02, window: int = 3) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Alerts when the rolling mean of hindsight regret over `window` decisions exceeds tau, and a retraining
    recommendation per model."""
    if rows is None or rows.empty:
        empty = pd.DataFrame(columns=["model", "t", "rolling_regret", "alert"])
        return empty, pd.DataFrame(columns=["model", "alerts", "recommendation"])
    r = rows.sort_values(["model", "t"]).copy()
    r["rolling_regret"] = r.groupby("model").regret_rel.transform(lambda s: s.rolling(window, min_periods=1).mean())
    r["alert"] = r.rolling_regret > tau_regret
    rec = []
    for m, g in r.groupby("model"):
        n = int(g.alert.sum())
        share = n / len(g)
        if share > 0.5:
            advice = "retrain or replace: decisions persistently worse than hindsight"
        elif n:
            advice = "refit on recent data when alerts occur (the agent does this automatically)"
        else:
            advice = "no action"
        rec.append({"model": m, "alerts": n, "share_of_decisions": share, "recommendation": advice})
    return r[["model", "t", "wape", "regret_rel", "rolling_regret", "alert"]], pd.DataFrame(rec)


def small_error_high_regret_example(rows: pd.DataFrame | None, tau_err=0.10, tau_regret=0.02) -> dict | None:
    if rows is None or rows.empty:
        return None
    c = rows[(rows.wape <= tau_err) & (rows.regret_rel > tau_regret)]
    if c.empty:
        return None
    r = c.sort_values("regret_rel", ascending=False).iloc[0]
    return {k: (float(v) if isinstance(v, (int, float, np.floating, np.integer)) else v) for k, v in r.items()}


# ------------------------------------------------------------------ agent: one cycle at a time
def make_approver(decisions: dict):
    """Simulated human approver backed by session state: decisions maps "t:reason" -> "approve" | "deny".
    Anything not decided yet is "pending" (the change is NOT applied)."""
    def approver(p: A.Proposal):
        d = decisions.get(f"{p.t}:{p.reason}")
        if d == "approve":
            return True, "human (simulated, this browser session)"
        if d == "deny":
            return False, "denied by human (simulated, this browser session)"
        return False, "pending human approval"
    return approver


def run_agent_cycles(key: str, Y: np.ndarray, cycles: int, start_offset: int = 0, decisions: dict | None = None,
                     approval_gb: float | None = None) -> dict:
    """Deterministically replay the agent for `cycles` hourly decisions (re-running from the start each time,
    so the result only depends on the inputs and the recorded human decisions)."""
    uc = U.USE_CASES[key]
    H = U.spec().horizon
    cfg = A.AgentConfig(consolidation=uc.consolidation, **({"approval_gb": approval_gb} if approval_gb is not None else {}))
    agent = A.PlacementAgent(Y, uc.topology, U.spec(), cfg, plan_kw=uc.plan_kw(), approver=make_approver(decisions or {}))
    start = uc.train_end + start_offset
    end = min(uc.T, start + H * max(1, cycles) + 1)
    dec, trace = agent.run(start, end, events=uc.events)
    last_t = int(dec.t.iloc[-1]) if len(dec) else start
    props = [p for p in agent.proposals if p["t"] == last_t]
    return {"decisions": dec, "trace": trace, "audit": pd.DataFrame(agent.audit), "proposals": props,
            "last_t": last_t, "agent": agent,
            "pending": [p for p in props if p["human_decision"] == "pending"]}


