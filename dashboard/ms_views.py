# ------------------------------------------------------------------ charts (all handle empty input)
def bottom_legend(fig: go.Figure) -> go.Figure:
    """Legend below the plot so it never overlaps the title."""
    fig.update_layout(legend=dict(orientation="h", yanchor="top", y=-0.22, xanchor="left", x=0),
                      margin=dict(b=90))
    return fig


def empty_figure(message: str) -> go.Figure:
    fig = go.Figure()
    fig.add_annotation(text=message, x=0.5, y=0.5, xref="paper", yref="paper", showarrow=False)
    fig.update_xaxes(visible=False)
    fig.update_yaxes(visible=False)
    return fig


def fig_predicted_vs_actual(df: pd.DataFrame | None, models, title: str) -> go.Figure:
    if df is None or df.empty:
        return empty_figure("No forecast data for this selection")
    fig = go.Figure(go.Scatter(x=df.window, y=df.actual, name="actual (" + HINDSIGHT + ")", mode="lines",
                               line=dict(width=3)))
    for m in models:
        if m in df:
            fig.add_trace(go.Scatter(x=df.window, y=df[m], name=m, mode="lines", line=dict(dash="dot")))
    fig.update_layout(title=title, xaxis_title="window (15 min)", yaxis_title="assignments per window")
    return bottom_legend(fig)


def fig_heatmap(mat: np.ndarray | None, title: str) -> go.Figure:
    if mat is None or np.size(mat) == 0:
        return empty_figure("No demand data")
    fig = go.Figure(go.Heatmap(z=mat, x=list(range(mat.shape[1])), y=list(range(mat.shape[0])), colorscale="Teal",
                               hovertemplate="layer %{y}, expert %{x}: %{z:,.0f}<extra></extra>"))
    fig.update_layout(title=title, xaxis_title="expert", yaxis_title="layer")
    return fig


def fig_regret_scatter(rows: pd.DataFrame | None, tau_err=0.10, tau_regret=0.02) -> go.Figure:
    if rows is None or rows.empty:
        return empty_figure("No regret data")
    fig = go.Figure()
    for m, g in rows.groupby("model"):
        fig.add_trace(go.Scatter(x=g.wape, y=g.regret_rel, mode="markers", name=m, marker=dict(size=9)))
    fig.add_vline(x=tau_err, line_dash="dash")
    fig.add_hline(y=tau_regret, line_dash="dash")
    fig.update_layout(title=f"Forecast error vs placement regret ({HINDSIGHT})", xaxis_title="WAPE",
                      yaxis_title="relative regret")
    return bottom_legend(fig)
