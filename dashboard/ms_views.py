# Plain-language meaning of each authoriser rule (moeplace/agent.py::Authoriser.check) and what would change it.
_CHECK_EXPLAIN = [
    ("constraints satisfied", "The new plan would break a hard rule: a GPU over capacity or memory, or data placed "
     "outside its allowed region (residency).", "Use a plan that respects every capacity, memory and residency rule."),
    ("forecast utilisation of new plan", "At least one device would be overloaded (more than 100% busy) under the "
     "forecast demand.", "Add capacity, spread replicas more widely, or wait for lower demand."),
    ("consolidation keeps forecast utilisation", "Switching devices off to save cost would leave the remaining ones "
     "busier than the target.", "Switch off fewer devices, or raise the utilisation target."),
    ("forecast objective gain", "The expected improvement is too small to be worth disrupting the running system.",
     "A larger demand shift (bigger expected gain) or a lower minimum-gain threshold."),
    ("transfer", "Copying the experts would take longer than allowed (a fixed share of the planning hour), so service "
     "would be disrupted for too long.", "Move fewer experts at once, use a faster link, or allow a longer transfer window."),
    ("mandatory change", "The change is required (e.g. a device failed), so it is not optional.", "—"),
]


def explain_check(text: str) -> tuple[str, str]:
    """(what it means, what would change it) for one authoriser check string."""
    for prefix, meaning, change in _CHECK_EXPLAIN:
        if text.startswith(prefix):
            return meaning, change
    return "Rule from the deterministic authoriser.", "See docs/GOVERNANCE.md."


def explain_proposal(p: dict) -> str | None:
    """Markdown explanation when a proposal is not applied (rejected or not approved by a human)."""
    failed = [t for t, ok in p["reasons"] if not ok]
    if failed:
        lines = [f"**Rejected by the authoriser** — {len(failed)} rule(s) failed:"]
        for t in failed:
            meaning, change = explain_check(t)
            lines.append(f"- *{t}* → {meaning} **What would change it:** {change}")
        lines.append("The current plan stays in place; nothing is copied.")
        return "\n".join(lines)
    if p.get("needs_human") and str(p.get("human_decision", "")).startswith(("deny", "denied")):
        return ("**Not applied: a human denied it.** All automatic rules passed, but the change was large (> 50 GB), "
                "touched a regulated (data-residency) site or switched devices off, so a person had to approve it, and "
                "they declined. The current plan stays in place.")
    if p.get("needs_human") and "pending" in str(p.get("human_decision", "")):
        return ("**Waiting for a human.** All automatic rules passed, but the change is large (> 50 GB), touches a "
                "data-residency site or switches devices off, so it is held until someone approves it.")
    return None


def blocked_reasons(dec: pd.DataFrame | None) -> pd.DataFrame:
    """Every authoriser check that FAILED, with the decision time and the outcome."""
    if dec is None or dec.empty or "reasons" not in dec:
        return pd.DataFrame(columns=["t", "proposal", "failed check", "what it means", "what would change it", "action"])
    out = []
    for r in dec.itertuples():
        for part in str(r.reasons).split(" | "):
            if part.startswith("FAIL: "):
                meaning, change = explain_check(part[6:])
                out.append({"t": r.t, "proposal": getattr(r, "proposal", ""), "failed check": part[6:],
                            "what it means": meaning, "what would change it": change, "action": r.action})
    return pd.DataFrame(out, columns=["t", "proposal", "failed check", "what it means", "what would change it", "action"])


