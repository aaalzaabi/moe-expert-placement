# ------------------------------------------------------------------ saved runs
def latest_run(prefix: str, root: Path | None = None) -> Path | None:
    root = Path(root or RUNS_DIR)
    if not root.exists():
        return None
    cands = [p for p in root.iterdir() if p.is_dir() and p.name.startswith(prefix + "-") and (p / "metadata.json").exists()]
    if not cands:
        return None
    return max(cands, key=lambda p: json.loads((p / "metadata.json").read_text()).get("created_utc", ""))


def load_csv(run_dir: Path | None, rel: str, producer: str) -> tuple[pd.DataFrame | None, str | None]:
    """(frame, None) or (None, user-facing message). Never raises for missing/corrupt files."""
    if run_dir is None:
        return None, f"No saved run found. Create one with `.venv/bin/python scripts/{producer}`."
    path = Path(run_dir) / rel
    if not path.exists():
        return None, f"`{path.name}` is missing from `{Path(run_dir).name}`. Re-run `.venv/bin/python scripts/{producer}`."
    try:
        df = pd.read_csv(path)
    except Exception as exc:  # corrupt / empty file
        return None, f"`{path.name}` could not be read ({type(exc).__name__}: {exc}). Re-run `scripts/{producer}`."
    if df.empty:
        return None, f"`{path.name}` is empty. Re-run `scripts/{producer}`."
    return df, None


def run_meta(run_dir: Path | None) -> dict:
    if run_dir is None or not (Path(run_dir) / "metadata.json").exists():
        return {}
    return json.loads((Path(run_dir) / "metadata.json").read_text())


def platform_label(meta: dict) -> str:
    """Human label for where planner timings were measured. Never claims Mac hardware for a Linux VM."""
    machine = str(meta.get("params", {}).get("machine") or meta.get("versions", {}).get("platform") or "")
    if not machine:
        return "measured on an unrecorded machine"
    if machine.lower().startswith(("macos", "darwin")):
        return f"measured on macOS ({machine})"
    if machine.lower().startswith("linux"):
        return f"measured on Linux ({machine}); not a macOS hardware measurement"
    return f"measured on {machine}"


